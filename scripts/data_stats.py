"""Generate docs/DATA.md: corpus/query statistics for Track 1 (TEMPO), data v1.1.

    python scripts/data_stats.py

Reads gold labels (qrels) for descriptive statistics only; nothing here feeds a system.
"""
from __future__ import annotations

import html
import random
import re
import statistics as st
from pathlib import Path

from reteco import SEED
from reteco.data import DOMAINS, REPO_ROOT, iter_corpus, load_qrels, load_queries

OUT = REPO_ROOT / "docs" / "DATA.md"
YEAR_RE = re.compile(r"(?<![\d.,])(1[0-9]{3}|20[0-2][0-9])(?![\d.,]\d)")
TAG_RE = re.compile(r"<[^>]+>")
EXAMPLE_DOMAINS = ["history", "bitcoin", "politics"]


def plain(text: str) -> str:
    return " ".join(html.unescape(TAG_RE.sub(" ", text)).split())


def short(text: str, n: int) -> str:
    text = plain(text)
    return text if len(text) <= n else text[:n].rsplit(" ", 1)[0] + " ..."


def pct(a: int, b: int) -> str:
    return f"{100 * a / b:.1f}%" if b else "-"


def main() -> None:
    rows, qlens, year = [], {}, {"q": [0, 0], "gold": [0, 0], "docs": [0, 0]}
    year_by_dom = {}
    examples = []
    rng = random.Random(SEED)
    for d in DOMAINS:
        qs = {s: load_queries(d, s) for s in ("train", "dev")}
        qrels = {s: load_qrels(d, s) for s in ("train", "dev")}
        gold = {doc for s in qrels for q in qrels[s].values() for doc in q}
        gold_text = {}
        n_docs = doc_words = doc_year = 0
        for doc_id, content in iter_corpus(d):
            n_docs += 1
            doc_words += len(content.split())
            doc_year += bool(YEAR_RE.search(content))
            if doc_id in gold:
                gold_text[doc_id] = content
        all_q = qs["train"] + qs["dev"]
        lens = [len(plain(q.query).split()) for q in all_q]
        qlens[d] = lens
        q_year = sum(bool(YEAR_RE.search(plain(q.query))) for q in all_q)
        g_year = sum(bool(YEAR_RE.search(t)) for t in gold_text.values())
        year_by_dom[d] = (q_year, len(all_q), g_year, len(gold_text), doc_year, n_docs)
        for k, v in zip(("q", "gold", "docs"), ((q_year, len(all_q)), (g_year, len(gold_text)),
                                                (doc_year, n_docs))):
            year[k][0] += v[0]
            year[k][1] += v[1]
        n_judg = sum(len(v) for s in qrels for v in qrels[s].values())
        rows.append((d, n_docs, round(doc_words / n_docs), len(qs["train"]), len(qs["dev"]),
                     n_judg / len(all_q)))
        if d in EXAMPLE_DOMAINS:
            cands = [q for q in qs["train"] if 15 <= len(plain(q.query).split()) <= 120]
            q = rng.choice(cands)
            examples.append((d, q, [gold_text[g] for g in list(qrels["train"][q.id])[:2]],
                             list(qrels["train"][q.id])))

    L = ["# Track 1 (TEMPO) data overview, v1.1", "",
         "Generated by `python scripts/data_stats.py` from `data/track1_tempo/`. "
         "Gold labels are used here for description only.", "",
         "## Per-domain counts", "",
         "| Domain | Documents | Avg doc words | Train queries | Dev queries | Gold docs / query |",
         "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for d, n, w, tr, dv, g in rows:
        L.append(f"| {d} | {n:,} | {w:,} | {tr} | {dv} | {g:.2f} |")
    L.append(f"| **total** | **{sum(r[1] for r in rows):,}** | | **{sum(r[3] for r in rows):,}** | "
             f"**{sum(r[4] for r in rows):,}** | |")

    allq = [x for v in qlens.values() for x in v]
    L += ["", "## Query length", "",
          "Words per query after stripping HTML tags (queries are StackExchange posts: a title "
          "followed by the HTML body). Train and dev combined.", "",
          "| Domain | Mean | Median | Min | Max |", "| --- | ---: | ---: | ---: | ---: |"]
    for d, v in list(qlens.items()) + [("**all**", allq)]:
        L.append(f"| {d} | {st.mean(v):.0f} | {st.median(v):.0f} | {min(v)} | {max(v)} |")

    L += ["", "## Explicit years", "",
          "Share of texts containing an explicit year, matched as a standalone 4-digit number in "
          "1000-2029 (not part of a longer number, decimal or thousands group). This is a rough "
          "lower-precision signal: quantities such as \"1500 BTC\" also match.", "",
          "| Domain | Queries with year | Gold docs with year | All docs with year |",
          "| --- | ---: | ---: | ---: |"]
    for d, (qy, qn, gy, gn, dy, dn) in year_by_dom.items():
        L.append(f"| {d} | {pct(qy, qn)} | {pct(gy, gn)} | {pct(dy, dn)} |")
    L.append(f"| **all** | **{pct(*year['q'])}** ({year['q'][0]}/{year['q'][1]}) | "
             f"**{pct(*year['gold'])}** ({year['gold'][0]:,}/{year['gold'][1]:,}) | "
             f"{pct(*year['docs'])} |")
    L += ["", "Gold docs are the unique documents judged relevant in train or dev qrels."]

    L += ["", "## Example queries (train)", "",
          f"Sampled with seed {SEED}. Text is HTML-stripped and shortened."]
    for d, q, golds, gold_ids in examples:
        L += ["", f"### {d}: `{q.id}`", "", f"> {short(q.query, 400)}", "",
              f"{len(gold_ids)} gold document(s). First {len(golds)}:", ""]
        for gid, t in zip(gold_ids, golds):
            L.append(f"- `{gid}`: {short(t, 300)}")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
